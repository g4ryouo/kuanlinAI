/** 週末但要上班的補班日（目前兩年都沒有） */
export const MAKEUP_WORKDAYS: string[] = [];

export const CALENDAR_YEARS = [2026, 2027];

const isWeekend = (date: string) => [0, 6].includes(new Date(`${date}T00:00:00Z`).getUTCDay());

export function holidayName(date: string): string | null {
  return HOLIDAYS[date] ?? null;
}

export function hasCalendar(date: string): boolean {
  return CALENDAR_YEARS.includes(Number(date.slice(0, 4)));
}

/** 這天是不是休息日：國定假日、或週末（補班日除外） */
export function isRestDay(date: string): boolean {
  if (MAKEUP_WORKDAYS.includes(date)) return false;
  return date in HOLIDAYS || isWeekend(date);
}
